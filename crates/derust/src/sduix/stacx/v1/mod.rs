//! Stac `v1` vocabulary (targets Stac `1.6.0`).
//!
//! The model mirrors `packages/stac_core` of the Stac repository at tag `v1.6.0`:
//!
//! * [`widgets`] — every widget, plus the closed [`widgets::Widget`] enum (`type` discriminator);
//! * [`actions`] — every action, plus the closed [`actions::Action`] enum (`actionType`);
//! * [`foundation`] — auxiliary types (colors, geometry, text styles, enums, ...);
//! * [`theme`] — [`theme::StacTheme`] and the `*ThemeData` types;
//! * [`dsl`] / [`prelude`] — shortcut constructors (`column()`, `text("..")`).
//!
//! Almost all of this module is generated by `tools/stac-inventory/gen_rust.py` from the Stac
//! sources (see that directory's README); only `foundation/colors/color.rs` and this file are
//! hand written. `inventory.json` lists every Stac component with its coverage status.

pub mod actions;
pub mod dsl;
pub mod foundation;
pub mod prelude;
pub mod state;
pub mod theme;
pub mod widgets;

/// Stac release this module targets.
pub const STAC_VERSION: &str = "1.6.0";

/// Commit of the Stac git tag `v1.6.0` this module was built against.
pub const STAC_TAG_COMMIT: &str = "b6cfe7cdb2bb4432e09d91ba23d6d72bdf721c01";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn constants_match_pinned_tag() {
        assert_eq!(STAC_VERSION, "1.6.0");
        assert_eq!(STAC_TAG_COMMIT.len(), 40);
    }
}
