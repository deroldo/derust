def clean_doc(lines, strip_type=False):
    """First paragraph of a Dart doc comment as plain text lines (safe for rustdoc)."""
    para = []
    for ln in lines:
        s = ln.strip()
        if not s:
            if para:
                break
            continue
        if s.startswith("```") or s.startswith("{@") or s.startswith("Type:") or s.startswith("Dart Example"):
            break
        para.append(s)
    text = " ".join(para)
    text = text.replace("[", "\\[").replace("]", "\\]").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"\s+", " ", text).strip()
    return [text] if text else []


def doc_lines(lines, indent):
    """`lines` is already cleaned (see clean_doc)."""
    return "".join("%s/// %s\n" % (indent, c) for c in lines)


