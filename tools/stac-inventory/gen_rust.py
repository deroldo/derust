#!/usr/bin/env python3
"""Generates the Rust model of Stac (`sduix::stacx::vN`) from a Stac checkout.

Usage:
    python3 tools/stac-inventory/gen_rust.py <stac-checkout> <crate-dir>

Writes (all marked `// @generated`; hand written files in the same directories are kept):
  <crate>/src/sduix/stacx/v1/{widgets,actions,foundation,theme}/...
  <crate>/src/sduix/stacx/v1/dsl.rs, prelude.rs
  <crate>/src/sduix/stacx/v1/inventory.json   (status/fixture of every component)
  <crate>/tests/sdui_stac_v1/fixtures/**.json and generated_*.rs tests

The Dart models are `json_serializable` classes, so the JSON contract is fully described by
the classes plus the generated `*.g.dart` files (see `stac_model.py`).
"""

import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stac_catalog  # noqa: E402
from stac_catalog import snake, pascal  # noqa: E402

MARKER = "// @generated by tools/stac-inventory/gen_rust.py - DO NOT EDIT"

RUST_KEYWORDS = set("""as break const continue crate else enum extern false fn for if impl in let loop match mod
move mut pub ref return self Self static struct super trait true type unsafe use where while async await dyn abstract
become box do final macro override priv typeof unsized virtual yield try gen""".split())
RESERVED_METHODS = {"new", "validate", "validate_at", "type_name", "serialize", "clone", "eq", "fmt",
                    "into", "from", "default", "ne"}

# Dart classes that are not modeled as Rust structs.
SKIP_CLASSES = {
    "StacOptions", "StacScreen", "StacThemeRef", "StacWidget", "StacAction", "StacElement", "DoubleConverter",
    "StacNavigator", "StacColors", "StacThemeTextStyles", "StacThemeData", "StacTextStyle", "StacShapeBorder",
}
# Classes that carry an actionType but are only nested (not registered as an action of their own).
NESTED_ONLY_ACTIONS = {"StacSnackBarAction"}

# Fields typed as raw JSON maps in Dart whose content is really a widget/action tree.
FIELD_TYPE_OVERRIDES = {
    ("StacDialogAction", "widget"): "StacWidget?",
    ("StacNavigateAction", "widgetJson"): "StacWidget?",
    ("StacNetworkResult", "action"): "StacAction",
    ("StacSnackBar", "content"): "StacWidget",
    ("StacSnackBar", "onVisible"): "StacAction?",
    ("StacTextSpan", "onTap"): "StacAction?",
    ("StacSetValueAction", "values"): "List<StateEntry>?",
    ("StacSetValue", "values"): "List<StateEntry>",
}
EXTRA_FIELDS = {
    "StacRoundedRectangleBorder": [("side", "StacBorderSide?")],
    "StacCircleBorder": [("side", "StacBorderSide?")],
    "StacContinuousRectangleBorder": [("side", "StacBorderSide?")],
    "StacBeveledRectangleBorder": [("side", "StacBorderSide?")],
}

NAME_OVERRIDES = {"StacColor": "Color"}
POLY_BASES = {"StacWidget": "Widget", "StacAction": "Action", "StacTextStyle": "TextStyle",
              "StacShapeBorder": "ShapeBorder"}


def rname(dart):
    if dart in NAME_OVERRIDES:
        return NAME_OVERRIDES[dart]
    if dart in POLY_BASES:
        return POLY_BASES[dart]
    return dart[4:] if dart.startswith("Stac") else dart


def ident(name):
    s = snake(name)
    return s + "_" if s in RUST_KEYWORDS else s


# --------------------------------------------------------------------------- types


def parse_type(t):
    t = t.strip()
    nullable = t.endswith("?")
    core = t.rstrip("?").strip()
    if core.startswith("List<"):
        inner = parse_type(core[5:-1])[0]
        return ("list", inner), nullable
    if core == "Map<String, dynamic>":
        return ("map",), nullable
    m = re.match(r"Map<int,\s*(\w+)>$", core)
    if m:
        return ("imap", ("named", m.group(1))), nullable
    if core in ("dynamic", "Object"):
        return ("json",), nullable
    if core in ("String", "double", "int", "bool"):
        return ("prim", core), nullable
    return ("named", core), nullable


class Gen:
    def __init__(self, stac_dir, crate_dir):
        self.crate = crate_dir
        lib_root = os.path.join(stac_dir, "packages", "stac_core", "lib")
        self.model, self.items = stac_catalog.build(lib_root)
        self.enums = {e["name"]: e for e in self.model["enums"]
                      if e["name"] not in ("WidgetType", "ActionType")}
        self.classes = {c["name"]: c for c in self.model["classes"]}
        self.items_by_name = {i["name"]: i for i in self.items}
        self.v1 = os.path.join(crate_dir, "src", "sduix", "stacx", "v1")
        self.tests = os.path.join(crate_dir, "tests", "sdui_stac_v1")
        self.written = set()
        self.fixture_names = {}
        self.fallbacks = []
        self.build_components()

    # ------------------------------------------------------------------ components
    def build_components(self):
        self.comps = {}  # dart name -> dict
        for name, c in self.classes.items():
            if name in SKIP_CLASSES:
                continue
            if c["json_keys"] is None:
                raise SystemExit("class %s has no generated toJson" % name)
            it = self.items_by_name[name]
            cat = it["category"]
            disc = None
            if c["extends"] == "StacWidget" and c["discriminator_getter"]:
                disc = ("type", stac_catalog.resolve_discriminator(c, self.enums))
            elif c["extends"] == "StacAction" and c["discriminator_getter"]:
                disc = ("actionType", stac_catalog.resolve_discriminator(c, self.enums))
            elif c.get("super_type"):
                disc = ("type", c["super_type"]["value"])
            fields = []
            for fl in c["fields"]:
                if fl["name"] in ("jsonData",):
                    continue
                fields.append(self.make_field(name, fl["name"], fl["dart_type"], fl["required"], fl["doc"],
                                              fl["nullable"], fl["has_default"]))
            for fname, ftype in EXTRA_FIELDS.get(name, []):
                fields.append(self.make_field(name, fname, ftype, False, [], True, False))
            keys = [k for k in c["json_keys"] if k not in ("type", "actionType")
                    or (k == "type" and any(f["json"] == "type" for f in fields))]
            have = {f["json"] for f in fields}
            if set(keys) != have:
                raise SystemExit("%s: toJson keys %s != fields %s" % (name, sorted(keys), sorted(have)))
            variant_of = None
            if disc and disc[0] == "type" and c["extends"] == "StacWidget":
                variant_of = "Widget"
            if disc and disc[0] == "actionType" and name not in NESTED_ONLY_ACTIONS:
                variant_of = "Action"
            if c["extends"] == "StacShapeBorder":
                variant_of = "ShapeBorder"
            if c["extends"] == "StacTextStyle":
                variant_of = "TextStyle"
            self.comps[name] = {
                "dart": name, "rust": rname(name), "cat": cat, "item": it, "fields": fields, "disc": disc,
                "variant_of": variant_of, "doc": clean_doc(c["doc"]), "dart_path": c["dart_path"],
                "needs_box": False,
            }
        for name, e in self.enums.items():
            self.comps[name] = {"dart": name, "rust": rname(name), "cat": self.items_by_name[name]["category"],
                                "item": self.items_by_name[name], "enum": e, "doc": clean_doc(e["doc"]),
                                "dart_path": e["dart_path"]}
        self.compute_boxing()
        self.box_large_fields()
        # unique rust names per category scope
        seen = {}
        for n, comp in self.comps.items():
            scope = "widgets" if comp["cat"] == "widget" else "actions" if comp["cat"] == "action" else "types"
            key = (scope, comp["rust"])
            if key in seen:
                raise SystemExit("rust name clash %s: %s vs %s" % (comp["rust"], n, seen[key]))
            seen[key] = n
        names = {}
        for n, comp in self.comps.items():
            names.setdefault(comp["rust"], []).append(n)
        for r, ns in names.items():
            if len(ns) > 1:
                raise SystemExit("rust name clash across categories %s: %s" % (r, ns))
        for r in ("Widget", "Action", "TextStyle", "ShapeBorder", "Color", "StateEntry"):
            if r in names:
                raise SystemExit("reserved name used: " + r)

    def compute_boxing(self):
        edges = {}
        for n, c in self.comps.items():
            if "fields" not in c:
                continue
            out = set()
            for f in c["fields"]:
                a = f["ast"]
                if a[0] == "named" and a[1] in self.comps and "fields" in self.comps[a[1]]:
                    out.add(a[1])
            edges[n] = out

        def reaches(src, dst, seen):
            for nxt in edges.get(src, ()):
                if nxt == dst:
                    return True
                if nxt not in seen:
                    seen.add(nxt)
                    if reaches(nxt, dst, seen):
                        return True
            return False

        for n, c in self.comps.items():
            for f in c.get("fields", []):
                a = f["ast"]
                f["boxed"] = bool(a[0] == "named" and a[1] in edges.get(n, ()) and reaches(a[1], n, set()) or
                                  (a[0] == "named" and a[1] == n))

    def estimate_size(self, ast, boxed, memo):
        k = ast[0]
        if k == "prim":
            return {"String": 32, "double": 16, "int": 16, "bool": 2}[ast[1]]
        if k in ("list", "map", "imap"):
            return 24
        if k == "json":
            return 32
        n = ast[1]
        if n in self.enums:
            return 2
        if n in POLY_BASES or n == "StacColor":
            return 32 if n == "StacColor" else 16
        if n == "StateEntry":
            return 56
        return 8 if boxed else self.comp_size(n, memo)

    def comp_size(self, name, memo):
        if name in memo:
            return memo[name]
        memo[name] = 8
        c = self.comps[name]
        total = sum(self.estimate_size(f["ast"], f.get("boxed", False), memo) for f in c["fields"])
        memo[name] = total
        return total

    def box_large_fields(self, limit=128):
        for _ in range(20):
            memo = {}
            changed = False
            for n, c in self.comps.items():
                for f in c.get("fields", []):
                    a = f["ast"]
                    if a[0] == "named" and a[1] in self.comps and "fields" in self.comps[a[1]] and not f.get("boxed"):
                        if self.comp_size(a[1], memo) > limit:
                            f["boxed"] = True
                            changed = True
            if not changed:
                return

    def field_type(self, f):
        t = self.rust_type(f["ast"])
        if f.get("boxed"):
            t = "Box<%s>" % t
        return "Option<%s>" % t if f["opt"] else t

    def field_conv(self, f, var="value"):
        c = self.setter_conv(f["ast"], var)
        return "Box::new(%s)" % c if f.get("boxed") else c

    def make_field(self, cls, name, dart_type, required, doc, nullable, has_default):
        dart_type = FIELD_OVERRIDES_TYPE(cls, name, dart_type)
        ast, nullable_t = parse_type(dart_type)
        nullable = nullable_t
        opt = (not required) or nullable
        if not required and not nullable and not has_default and False:
            opt = True
        rid = ident(name)
        if rid in RESERVED_METHODS:
            raise SystemExit("field %s.%s collides with an inherent method" % (cls, name))
        return {"json": name, "ident": rid, "ast": ast, "opt": opt, "required": required and not nullable,
                "doc": clean_doc(doc, strip_type=True), "dart_type": dart_type}

    # ------------------------------------------------------------------ rust types
    def rust_named(self, dart):
        if dart in NAME_OVERRIDES or dart in POLY_BASES:
            return rname(dart)
        if dart == "StateEntry":
            return "StateEntry"
        if dart not in self.comps:
            raise SystemExit("unknown type " + dart)
        return rname(dart)

    def rust_type(self, ast, in_list=False):
        k = ast[0]
        if k == "prim":
            return {"String": "String" if in_list else "Dyn<String>", "double": "f64", "int": "i64",
                    "bool": "bool"}[ast[1]]
        if k == "named":
            return self.rust_named(ast[1])
        if k == "list":
            return "Vec<%s>" % self.rust_type(ast[1], True)
        if k == "map":
            return "serde_json::Map<String, serde_json::Value>"
        if k == "imap":
            return "std::collections::BTreeMap<i64, %s>" % self.rust_type(ast[1], True)
        if k == "json":
            return "serde_json::Value"
        raise AssertionError(ast)

    def is_enum(self, ast):
        return ast[0] == "named" and ast[1] in self.enums

    def needs_validate(self, ast):
        k = ast[0]
        if k == "prim":
            return ast[1] in ("String", "double")
        if k == "named":
            return not self.is_enum(ast)
        if k == "list":
            inner = ast[1]
            if inner[0] == "prim":
                return inner[1] == "double"
            return self.needs_validate(inner)
        if k == "imap":
            return self.needs_validate(ast[1])
        return False

    def setter_param(self, ast):
        k = ast[0]
        if k == "prim" and ast[1] == "bool":
            return "bool"
        if k == "imap":
            return self.rust_type(ast)
        if k == "list":
            inner = self.rust_type(ast[1], True)
            return "impl IntoIterator<Item = impl Into<%s>>" % inner
        return "impl Into<%s>" % self.rust_type(ast)

    def setter_conv(self, ast, var="value"):
        k = ast[0]
        if k == "prim" and ast[1] == "bool":
            return var
        if k == "imap":
            return var
        if k == "list":
            return "%s.into_iter().map(Into::into).collect()" % var
        return "%s.into()" % var

    # ------------------------------------------------------------------ emit structs
    def header(self):
        return (MARKER + "\n"
                "#![allow(unused_imports, clippy::too_many_arguments, clippy::new_without_default, "
                "clippy::large_enum_variant, clippy::enum_variant_names, clippy::module_name_repetitions)]\n"
                "use crate::sduix::stacx::common::*;\n"
                "use crate::sduix::stacx::v1::{actions::*, foundation::*, theme::*, widgets::*};\n"
                "use serde::ser::{Serialize, SerializeMap, Serializer};\n\n")

    def emit_struct(self, comp):
        r = comp["rust"]
        out = [self.header()]
        out.append(doc_lines(comp["doc"], "") or "/// Stac `%s` model.\n" % comp["dart"])
        out.append("#[derive(Debug, Clone, PartialEq)]\npub struct %s {\n" % r)
        for f in comp["fields"]:
            out.append(doc_lines(f["doc"], "    "))
            out.append("    pub %s: %s,\n" % (f["ident"], self.field_type(f)))
        out.append("}\n\n")
        req = [f for f in comp["fields"] if not f["opt"]]
        out.append("impl %s {\n" % r)
        if comp["disc"]:
            out.append("    /// Value of the `%s` discriminator.\n    pub const TYPE: &'static str = \"%s\";\n\n"
                       % comp["disc"])
        out.append("    /// Creates the model with only its required fields set.\n")
        params = ", ".join("%s: %s" % (f["ident"], self.setter_param(f["ast"])) for f in req)
        out.append("    pub fn new(%s) -> Self {\n        Self {\n" % params)
        for f in comp["fields"]:
            if f["opt"]:
                out.append("            %s: None,\n" % f["ident"])
            else:
                out.append("            %s: %s,\n" % (f["ident"], self.field_conv(f, f["ident"])))
        out.append("        }\n    }\n")
        for f in comp["fields"]:
            if not f["opt"] and False:
                continue
            doc = doc_lines(f["doc"], "    ") or "    /// Sets `%s`.\n" % f["json"]
            out.append("\n" + doc)
            conv = self.field_conv(f)
            val = "Some(%s)" % conv if f["opt"] else conv
            out.append("    pub fn %s(mut self, value: %s) -> Self {\n        self.%s = %s;\n        self\n    }\n"
                       % (f["ident"], self.setter_param(f["ast"]), f["ident"], val))
        out.append("}\n\n")
        # Serialize
        out.append("impl Serialize for %s {\n" % r)
        out.append("    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {\n")
        out.append("        let mut map = serializer.serialize_map(None)?;\n")
        if comp["disc"]:
            out.append("        map.serialize_entry(\"%s\", \"%s\")?;\n" % comp["disc"])
        for f in comp["fields"]:
            if f["opt"]:
                out.append("        if let Some(value) = &self.%s {\n            map.serialize_entry(\"%s\", value)?;\n"
                           "        }\n" % (f["ident"], f["json"]))
            else:
                out.append("        map.serialize_entry(\"%s\", &self.%s)?;\n" % (f["json"], f["ident"]))
        out.append("        map.end()\n    }\n}\n\n")
        # Validate
        out.append("impl Validate for %s {\n" % r)
        vf = [f for f in comp["fields"] if self.needs_validate(f["ast"])]
        pn = "path" if vf else "_path"
        isn = "issues" if (vf or self.custom_checks(comp)) else "_issues"
        out.append("    fn validate_at(&self, %s: &Path<'_>, %s: &mut Vec<ValidationIssue>) {\n" % (pn, isn))
        for f in vf:
            out.append("        self.%s.validate_at(&path.key(\"%s\"), issues);\n" % (f["ident"], f["json"]))
        out.append(self.custom_checks(comp))
        out.append("    }\n}\n")
        if comp["disc"] and comp["cat"] in ("widget", "action"):
            kind = "Widget" if comp["disc"][0] == "type" else "Action"
            out.append("\nimpl StacNode for %s {\n    const KIND: NodeKind = NodeKind::%s;\n"
                       "    const TYPE_NAME: &'static str = \"%s\";\n}\n" % (r, kind, comp["disc"][1]))
        if comp["variant_of"]:
            base = comp["variant_of"]
            out.append("\nimpl From<%s> for %s {\n    fn from(value: %s) -> Self {\n        %s::%s(Box::new(value))\n"
                       "    }\n}\n" % (r, base, r, base, r))
        return "".join(out)

    def custom_checks(self, comp):
        if comp["dart"] == "StacBadge":
            return ("        if let Some(count) = self.count.as_ref() {\n"
                    "            if *count < 0 {\n"
                    "                issues.push(ValidationIssue::new(&path.key(\"count\"), "
                    "\"count must be non-negative\"));\n            }\n        }\n"
                    "        if let Some(max_count) = self.max_count.as_ref() {\n"
                    "            if *max_count <= 0 {\n"
                    "                issues.push(ValidationIssue::new(&path.key(\"maxCount\"), "
                    "\"maxCount must be positive\"));\n            }\n        }\n")
        return ""

    def emit_enum(self, comp):
        e = comp["enum"]
        out = [self.header()]
        out.append(doc_lines(comp["doc"], "") or "/// Stac `%s`.\n" % e["name"])
        out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize)]\npub enum %s {\n" % comp["rust"])
        for v, j in zip(e["values"], e["json_values"]):
            out.append("    #[serde(rename = \"%s\")]\n    %s,\n" % (j, pascal(v)))
        out.append("}\n\nimpl %s {\n    /// Value written to the JSON.\n    pub const fn as_str(self) -> &'static str {\n"
                   "        match self {\n" % comp["rust"])
        for v, j in zip(e["values"], e["json_values"]):
            out.append("            Self::%s => \"%s\",\n" % (pascal(v), j))
        out.append("        }\n    }\n}\n")
        return "".join(out)

    def emit_poly_enum(self, rust, tag_key, members, doc, custom=None):
        """members: list of (variant, json_value); custom: (trait, constructor) adds a `Custom`
        variant holding application defined nodes (see `common/custom.rs`)."""
        out = [self.header(), doc, "#[derive(Debug, Clone, PartialEq)]\npub enum %s {\n" % rust]
        for v, _ in members:
            out.append("    %s(Box<%s>),\n" % (v, v))
        if custom:
            out.append("    /// Node of a custom parser registered in the Flutter app (see [`%s`]).\n"
                       "    Custom(CustomNode),\n" % custom[0])
        out.append("}\n\n")
        extra = ["Custom"] if custom else []
        out.append("impl Serialize for %s {\n    fn serialize<S: Serializer>(&self, serializer: S) -> "
                   "Result<S::Ok, S::Error> {\n        match self {\n" % rust)
        for v in [m[0] for m in members] + extra:
            out.append("            %s::%s(value) => value.serialize(serializer),\n" % (rust, v))
        out.append("        }\n    }\n}\n\n")
        out.append("impl Validate for %s {\n    fn validate_at(&self, path: &Path<'_>, issues: &mut Vec<ValidationIssue>) {\n"
                   "        match self {\n" % rust)
        for v in [m[0] for m in members] + extra:
            out.append("            %s::%s(value) => value.validate_at(path, issues),\n" % (rust, v))
        out.append("        }\n    }\n}\n\n")
        out.append("impl %s {\n    /// Value of the `%s` discriminator of the wrapped node.\n"
                   "    pub fn type_name(&self) -> &'static str {\n        match self {\n" % (rust, tag_key))
        for v, j in members:
            out.append("            %s::%s(_) => \"%s\",\n" % (rust, v, j))
        if custom:
            out.append("            %s::Custom(value) => value.type_name(),\n" % rust)
        out.append("        }\n    }\n}\n")
        if custom:
            out.append("\nimpl<T: %s> From<T> for %s {\n    fn from(value: T) -> Self {\n"
                       "        %s::Custom(CustomNode::%s(value))\n    }\n}\n" % (custom[0], rust, rust, custom[1]))
        return "".join(out)

    # ------------------------------------------------------------------ layout
    def path_for(self, comp):
        s = snake(comp["rust"])
        if s in RUST_KEYWORDS:
            s += "_"
        cat = comp["cat"]
        if cat == "widget":
            return ("widgets", None, s)
        if cat == "action":
            return ("actions", None, s)
        if cat == "theme":
            return ("theme", None, s)
        group = comp["dart_path"].split(os.sep)[1]
        return ("foundation", group, s)

    def write(self, path, content):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        self.written.add(os.path.abspath(path))

    def run(self):
        modules = {}  # (top, group) -> list of (file, [types])
        for dart, comp in sorted(self.comps.items()):
            top, group, fname = self.path_for(comp)
            if "enum" in comp:
                src = self.emit_enum(comp)
            else:
                src = self.emit_struct(comp)
            base = [self.v1, top] + ([group] if group else []) + [fname + ".rs"]
            self.write(os.path.join(*base), src)
            modules.setdefault((top, group), []).append((fname, comp["rust"]))
        # polymorphic enums
        widgets = sorted((c for c in self.comps.values() if c.get("variant_of") == "Widget"), key=lambda c: c["rust"])
        actions = sorted((c for c in self.comps.values() if c.get("variant_of") == "Action"), key=lambda c: c["rust"])
        shapes = sorted((c for c in self.comps.values() if c.get("variant_of") == "ShapeBorder"), key=lambda c: c["rust"])
        styles = sorted((c for c in self.comps.values() if c.get("variant_of") == "TextStyle"), key=lambda c: c["rust"])
        self.write(os.path.join(self.v1, "widgets", "widget.rs"), self.emit_poly_enum(
            "Widget", "type", [(c["rust"], c["disc"][1]) for c in widgets],
            "/// Any Stac widget (discriminated by `type`), or a [`CustomWidget`] of the app.\n",
            custom=("CustomWidget", "widget")))
        modules[("widgets", None)].append(("widget", "Widget"))
        self.write(os.path.join(self.v1, "actions", "action.rs"), self.emit_poly_enum(
            "Action", "actionType", [(c["rust"], c["disc"][1]) for c in actions],
            "/// Any Stac action (discriminated by `actionType`), or a [`CustomAction`] of the app.\n",
            custom=("CustomAction", "action")))
        modules[("actions", None)].append(("action", "Action"))
        self.write(os.path.join(self.v1, "foundation", "borders", "shape_border.rs"), self.emit_poly_enum(
            "ShapeBorder", "type", [(c["rust"], c["disc"][1]) for c in shapes],
            "/// Any Stac shape border (discriminated by `type`).\n"))
        modules[("foundation", "borders")].append(("shape_border", "ShapeBorder"))
        self.write(os.path.join(self.v1, "foundation", "text", "text_style.rs"), self.emit_poly_enum(
            "TextStyle", "type", [(c["rust"], c["disc"][1]) for c in styles],
            "/// Any Stac text style (custom or Material theme style, discriminated by `type`).\n"))
        modules[("foundation", "text")].append(("text_style", "TextStyle"))
        # hand written files
        for (top, group), mods in list(modules.items()):
            d = os.path.join(*([self.v1, top] + ([group] if group else [])))
            for f in sorted(os.listdir(d)):
                p = os.path.abspath(os.path.join(d, f))
                if f.endswith(".rs") and f != "mod.rs" and p not in self.written:
                    mods.append((f[:-3], None))
        # mod files
        groups = {}
        self.tops = {}
        for (top, group), mods in modules.items():
            mods = sorted(set(mods))
            body = [MARKER + "\n#![allow(clippy::module_inception)]\n"]
            for fname, _ in mods:
                body.append("mod %s;\n" % fname)
            body.append("\n")
            for fname, rust in mods:
                if rust is None and fname.endswith("_ext"):
                    continue  # hand written `impl` blocks only
                body.append("pub use %s::*;\n" % fname if rust is None else "pub use %s::%s;\n" % (fname, rust))
            if top == "theme" and group is None:
                body.append("\n/// Global Stac theme (`StacTheme`).\npub type StacTheme = Theme;\n")
            if group:
                groups.setdefault(top, []).append(group)
                self.write(os.path.join(self.v1, top, group, "mod.rs"), "".join(body))
            else:
                modules_top = body
                self.tops[top] = modules_top
        for top in groups:
            self.tops.setdefault(top, [MARKER + "\n"])
        for top, body in self.tops.items():
            gs = sorted(groups.get(top, []))
            head = [MARKER + "\n#![allow(clippy::module_inception)]\n"]
            for g in gs:
                head.append("mod %s;\n" % g)
            tail = ["pub use %s::*;\n" % g for g in gs]
            text = "".join(head) + "".join(body[1:]) + ("\n" + "".join(tail) if tail else "")
            self.write(os.path.join(self.v1, top, "mod.rs"), text)
        self.emit_dsl(widgets, actions)
        self.emit_fixtures_and_tests()
        self.update_inventory()
        self.rustfmt()

    def rustfmt(self):
        import subprocess
        files = sorted(p for p in self.written if p.endswith(".rs"))
        for i in range(0, len(files), 100):
            subprocess.run(["rustfmt", "--edition", "2021"] + files[i:i + 100], check=True)

    # ------------------------------------------------------------------ dsl
    def emit_dsl(self, widgets, actions):
        out = [MARKER + "\n"
               "//! Shortcut constructors, e.g. `column()`, `text(\"Hello\")`, `navigate()`.\n\n"
               "#![allow(unused_imports, clippy::too_many_arguments)]\n"
               "use crate::sduix::stacx::common::*;\n"
               "use crate::sduix::stacx::v1::{actions::*, foundation::*, theme::*, widgets::*};\n\n"]
        used = set()
        for comp in widgets + actions:
            isw = comp["variant_of"] == "Widget"
            name = snake(comp["rust"])
            if not isw and name.endswith("_action"):
                short = name[: -len("_action")]
                if short not in used and short not in {snake(w["rust"]) for w in widgets}:
                    name = short
            if name in RUST_KEYWORDS:
                name += "_"
            used.add(name)
            req = [f for f in comp["fields"] if not f["opt"]]
            params = ", ".join("%s: %s" % (f["ident"], self.setter_param(f["ast"])) for f in req)
            args = ", ".join(f["ident"] for f in req)
            out.append("/// Shortcut for [`%s::new`].\npub fn %s(%s) -> %s {\n    %s::new(%s)\n}\n\n"
                       % (comp["rust"], name, params, comp["rust"], comp["rust"], args))
        self.write(os.path.join(self.v1, "dsl.rs"), "".join(out))

    # ------------------------------------------------------------------ fixtures
    def emit_fixtures_and_tests(self):
        from fixtures import FixtureBuilder  # local module
        fb = FixtureBuilder(self)
        fb.run()

    def update_inventory(self):
        path = os.path.join(self.v1, "inventory.json")
        doc = json.load(open(path, encoding="utf-8"))
        for it in doc["items"]:
            fx = self.fixture_names.get(it["name"])
            if fx:
                it["status"] = "supported"
                it["fixture"] = fx
                it.pop("notes", None)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(doc, f, indent=2)
            f.write("\n")


